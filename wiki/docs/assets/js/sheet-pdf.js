/* Fill in the real character sheet, in the browser.
 *
 * The Download button hands back the designed one-page sheet -- the same PDF
 * that sits on the Downloads page, typeface, red labels, reference box and all
 * -- with what you typed written onto its ruled lines. It is not a lookalike
 * built from scratch; it is that exact file with an overlay appended.
 *
 * How, with no server: a PDF can be extended by an "incremental update". You
 * leave the original bytes untouched, append the objects you want to add or
 * replace, then append a new cross-reference table that points at them and
 * chains back to the old one with /Prev. Readers use the last table they find,
 * so the appended page object wins. That is the whole trick, and it means we
 * never have to parse or rewrite the designed sheet -- only read a few numbers
 * out of it.
 *
 * Nothing is uploaded. The sheet is fetched from this same origin (the service
 * worker keeps a copy, so it works at a table with no signal), filled in on
 * this machine, and handed to the browser as a download.
 *
 * Object numbers are read from the file at runtime rather than hardcoded,
 * because the sheet is regenerated by tools/build_pdf.py on every deploy and
 * Chrome does not promise to number things the same way twice. The ruled-line
 * COORDINATES are hardcoded below, and tools/check-sheet-fields.py fails the
 * build if they ever stop matching the real sheet.
 */
(function () {
  'use strict';

  var SHEET_URL = '/downloads/does-play-dice-character-sheet.pdf';

  /* ---- Where the ruled lines are, in PDF points from the bottom-left -------
     Extracted from the sheet itself; see tools/check-sheet-fields.py. */
  var RULES = {
    'name':        [39.7, 659.3, 261.0],
    'played-by':  [312.7, 659.3, 260.2],
    'bg-1':        [39.7, 612.8, 533.2],
    'bg-2':        [39.7, 586.5, 533.2],
    'school':      [39.7, 540.0, 261.0],
    'connections':[312.7, 540.0, 260.2],
    'habits-1':    [39.7, 494.3, 533.2],
    'habits-2':    [39.7, 467.3, 533.2],
    'notes-1':     [39.7, 246.8, 533.2],
    'notes-2':     [39.7, 224.3, 533.2],
    'notes-3':     [39.7, 201.0, 533.2],
    'notes-4':     [39.7, 178.5, 533.2],
    /* The die cells already have a grey "d" printed on them, so only the size
       goes here -- set on that glyph's own baseline, just past where it ends, so
       "d" + "8" reads as one word rather than two things near each other. */
    'die-1':      [343.5, 415.5, 34.0],
    'die-2':      [343.5, 386.3, 34.0],
    'die-3':      [343.5, 357.0, 34.0]
  };

  /* Which ruled lines each labelled block on the web page flows into. Matched on
     the label so that reordering the markdown cannot silently misfile answers. */
  var BLOCKS = [
    { match: /character name/i,  rules: ['name'] },
    { match: /played by/i,       rules: ['played-by'] },
    { match: /background/i,      rules: ['bg-1', 'bg-2'] },
    { match: /school or job/i,   rules: ['school'] },
    { match: /habits/i,          rules: ['habits-1', 'habits-2'] },
    { match: /connections/i,     rules: ['connections'] },
    { match: /notes/i,           rules: ['notes-1', 'notes-2', 'notes-3', 'notes-4'] }
  ];

  var DIE_RULES = ['die-1', 'die-2', 'die-3'];

  /* ---- Type metrics ------------------------------------------------------- */

  var W = ('278 278 355 556 556 889 667 191 333 333 389 584 278 333 278 278 ' +
           '556 556 556 556 556 556 556 556 556 556 278 278 584 584 584 556 ' +
           '1015 667 667 722 722 667 611 778 722 278 500 667 556 833 722 778 ' +
           '667 778 722 667 611 722 667 944 667 667 611 278 278 278 469 556 ' +
           '333 556 556 500 556 556 278 556 556 222 222 500 222 833 556 556 ' +
           '556 556 333 500 278 556 500 722 500 500 500 334 260 334 584'
          ).split(' ').map(Number);

  var WINANSI = {
    0x2018: 0x91, 0x2019: 0x92, 0x201A: 0x82, 0x201C: 0x93, 0x201D: 0x94,
    0x201E: 0x84, 0x2013: 0x96, 0x2014: 0x97, 0x2026: 0x85, 0x2022: 0x95,
    0x2020: 0x86, 0x2021: 0x87, 0x2030: 0x89, 0x20AC: 0x80, 0x2122: 0x99,
    0x02C6: 0x88, 0x02DC: 0x98, 0x2039: 0x8B, 0x203A: 0x9B
  };

  function encode(str) {
    var out = '';
    for (var i = 0; i < str.length; i++) {
      var c = str.charCodeAt(i);
      if (c === 9) { out += ' '; continue; }
      if (c >= 32 && c <= 255) { out += String.fromCharCode(c); continue; }
      out += String.fromCharCode(WINANSI[c] || 63);
    }
    return out;
  }

  function charWidth(code) {
    return (code >= 32 && code <= 126) ? W[code - 32] : 556;
  }

  function measure(str, size) {
    var t = 0;
    for (var i = 0; i < str.length; i++) t += charWidth(str.charCodeAt(i));
    return t * size / 1000;
  }

  function wrap(str, size, maxWidth) {
    var words = String(str).split(/\s+/).filter(Boolean);
    var lines = [], line = '';
    while (words.length) {
      var word = words.shift();
      var candidate = line ? line + ' ' + word : word;
      if (measure(candidate, size) <= maxWidth) { line = candidate; continue; }
      if (line) { lines.push(line); line = ''; words.unshift(word); continue; }
      var cut = word.length;
      while (cut > 1 && measure(word.slice(0, cut), size) > maxWidth) cut--;
      lines.push(word.slice(0, cut));
      words.unshift(word.slice(cut));
    }
    if (line) lines.push(line);
    return lines;
  }

  function escapePdf(s) { return s.replace(/[\\()]/g, '\\$&'); }

  /* Lay a block's answers onto the lines it has. Each answer keeps its own line,
     as it does on screen. If the whole block will not fit, the type shrinks --
     down to a floor, past which the rest is dropped rather than overprinted. */
  function layoutBlock(values, ruleNames) {
    var width = RULES[ruleNames[0]][2] - 6;
    for (var size = 10; size >= 7; size -= 0.5) {
      var lines = [];
      values.forEach(function (v) {
        if (v) lines = lines.concat(wrap(v, size, width));
      });
      if (lines.length <= ruleNames.length || size === 7) {
        return { size: size, lines: lines.slice(0, ruleNames.length) };
      }
    }
    return { size: 7, lines: [] };
  }

  /* ---- Reading the numbers we need out of the designed sheet --------------- */

  function parse(pdf) {
    var tail = pdf.slice(-2048);
    var sx = /startxref\s+(\d+)\s*%%EOF\s*$/.exec(tail);
    var size = /\/Size\s+(\d+)/.exec(tail);
    var root = /\/Root\s+(\d+)\s+0\s+R/.exec(tail);
    if (!sx || !size || !root) throw new Error('cannot read the sheet trailer');

    /* The page object: the one whose dictionary is /Type /Page, not /Type /Pages. */
    var re = /(\d+)\s+0\s+obj\s*(<<[\s\S]*?>>)\s*(?:stream|endobj)/g, m, page = null;
    while ((m = re.exec(pdf))) {
      if (/\/Type\s*\/Page[^s]/.test(m[2])) { page = { num: +m[1], dict: m[2] }; break; }
    }
    if (!page) throw new Error('cannot find the page');
    if (!/\/Font\s*<</.test(page.dict)) throw new Error('page fonts are not inline');

    return {
      prev: +sx[1], size: +size[1], root: +root[1],
      pageNum: page.num, pageDict: page.dict
    };
  }

  function build(pdf, info, ops) {
    var q = info.size, Q = q + 1, ov = Q + 1, font = ov + 1;

    /* Re-emit the page with our overlay appended to its contents and our font
       added to its resources. Fencing the original in q/Q matters: Chrome leaves
       a scale transform in effect at the end of its stream, and without the
       fence every coordinate below would be three-quarter size and in the wrong
       corner. */
    var dict = info.pageDict
      .replace(/\/Font\s*<</, '/Font <</F99 ' + font + ' 0 R ')
      .replace(/\/Contents\s+(\d+)\s+0\s+R/,
               '/Contents [' + q + ' 0 R $1 0 R ' + Q + ' 0 R ' + ov + ' 0 R]')
      .replace(/\/Contents\s*\[([^\]]*)\]/,
               '/Contents [' + q + ' 0 R $1 ' + Q + ' 0 R ' + ov + ' 0 R]');

    var overlay = ops.join('\n');
    var parts = [
      [info.pageNum, dict],
      [q,    '<< /Length 1 >>\nstream\nq\nendstream'],
      [Q,    '<< /Length 1 >>\nstream\nQ\nendstream'],
      [ov,   '<< /Length ' + overlay.length + ' >>\nstream\n' + overlay + '\nendstream'],
      [font, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica ' +
             '/Encoding /WinAnsiEncoding >>']
    ];

    var out = pdf.charAt(pdf.length - 1) === '\n' ? pdf : pdf + '\n';
    var offsets = {};
    parts.forEach(function (p) {
      offsets[p[0]] = out.length;
      out += p[0] + ' 0 obj\n' + p[1] + '\nendobj\n';
    });

    function ten(n) { return ('0000000000' + n).slice(-10); }
    var at = out.length;
    var x = 'xref\n' + info.pageNum + ' 1\n' + ten(offsets[info.pageNum]) + ' 00000 n \n' +
            q + ' 4\n';
    [q, Q, ov, font].forEach(function (n) { x += ten(offsets[n]) + ' 00000 n \n'; });
    x += 'trailer\n<< /Size ' + (font + 1) + ' /Root ' + info.root +
         ' 0 R /Prev ' + info.prev + ' >>\nstartxref\n' + at + '\n%%EOF\n';

    return out + x;
  }

  /* ---- Putting the answers on the page ------------------------------------ */

  function overlayFor(model) {
    var ops = ['0.04 0.04 0.04 rg'];

    function put(ruleName, text, size) {
      var r = RULES[ruleName];
      if (!r || !text) return;
      ops.push('BT /F99 ' + size + ' Tf ' + (r[0] + 3).toFixed(1) + ' ' +
               (r[1] + 4).toFixed(1) + ' Td (' + escapePdf(encode(text)) + ') Tj ET');
    }

    model.groups.forEach(function (group) {
      if (group.kind === 'skills') {
        group.rows.forEach(function (row, i) {
          if (!DIE_RULES[i] || !row.die) return;
          /* The sheet already prints a grey "d"; only the size goes after it. */
          var v = String(row.die).replace(/^\s*d/i, '').trim();
          var r = RULES[DIE_RULES[i]];
          if (!v) return;
          ops.push('BT /F99 12 Tf ' + r[0].toFixed(1) + ' ' + r[1].toFixed(1) +
                   ' Td (' + escapePdf(encode(v)) + ') Tj ET');
        });
        return;
      }
      var block = null;
      for (var i = 0; i < BLOCKS.length; i++) {
        if (BLOCKS[i].match.test(group.label)) { block = BLOCKS[i]; break; }
      }
      if (!block) return;
      var laid = layoutBlock(group.values, block.rules);
      laid.lines.forEach(function (line, j) { put(block.rules[j], line, laid.size); });
    });

    return ops;
  }

  /* ---- The button --------------------------------------------------------- */

  window.dpdSheetPDF = function (model, filename) {
    return fetch(SHEET_URL, { credentials: 'omit' })
      .then(function (res) {
        if (!res.ok) throw new Error('the sheet could not be fetched (' + res.status + ')');
        return res.arrayBuffer();
      })
      .then(function (buf) {
        var bytes = new Uint8Array(buf), pdf = '';
        for (var i = 0; i < bytes.length; i += 8192) {
          pdf += String.fromCharCode.apply(null, bytes.subarray(i, i + 8192));
        }
        var out = build(pdf, parse(pdf), overlayFor(model));

        var blob = new Uint8Array(out.length);
        for (var j = 0; j < out.length; j++) blob[j] = out.charCodeAt(j) & 0xFF;
        var url = URL.createObjectURL(new Blob([blob], { type: 'application/pdf' }));
        var a = document.createElement('a');
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
      });
  };
})();
